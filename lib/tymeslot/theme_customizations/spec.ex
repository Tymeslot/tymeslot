defmodule Tymeslot.ThemeCustomizations.Spec do
  @moduledoc """
  The customisation contract every booking theme declares.

  A spec says which option groups a theme offers, what its defaults are, how a
  write is validated and how the stored settings become CSS tokens. It is the
  only place a theme's customisation defaults and rules live: every write
  (dashboard, uploads, onboarding, account provisioning) goes through
  `changeset/2`, and the booking page reads through `tokens/2`.

  A spec `use`s this module and writes `option_groups/0` and `defaults/0`.
  The rest is generated from its groups (see
  `Tymeslot.ThemeCustomizations.OptionGroup`): `changeset/2` runs every
  group's `changeset/3` in declaration order, `asset_fields/0` joins every
  group's `asset_fields/1`, and `tokens/2` is `Specs.tokens/3`, which
  folds every group's optional `tokens/4` in declaration order and adds every
  group's media (`Specs.media/2` merges each group's optional `media/2` into
  `Tokens.media`). All three stay
  overridable; a spec with tokens of its own overrides `tokens/2` and starts
  from `Specs.tokens/3`. It also generates `onboarding_choices/0` from the
  palette group, which a spec may override.

  `Spec` is only the contract, so `use Spec` costs a theme no compile-time
  coupling: once a spec has compiled it asks the spec's groups for their
  `types/0`, and refuses the spec (a `CompileError`) when two groups declare
  the same setting or share a `key:`, but those calls are not in the spec's
  code. The questions asked of a spec (`group/2`, `for_theme/1` and the
  rest) live in `Tymeslot.ThemeCustomizations.Specs`.

  Each theme names its spec in its `Tymeslot.Themes.Catalog` entry
  (`customization_spec:`).
  """

  alias Ecto.Changeset
  alias Tymeslot.ThemeCustomizations.OptionGroup
  alias Tymeslot.ThemeCustomizations.Specs
  alias Tymeslot.ThemeCustomizations.Tokens

  @typedoc "A kind of background a theme can show."
  @type background_kind :: :gradient | :color | :image | :video

  @typedoc "Stored settings with string keys, as `ThemeCustomizations.to_map/1` returns them."
  @type settings :: %{optional(String.t()) => term()}

  @typedoc "Per-page-view overrides, such as an embed's accent colour. Empty when there are none."
  @type overrides :: %{optional(atom()) => term()}

  @typedoc """
  What an uploaded asset field stores: an image, a video (transcoded into
  variants) or WebVTT captions.
  """
  @type asset_kind :: :image | :video | :captions

  @typedoc """
  What the onboarding wizard offers for a theme: the option group and field a
  choice writes (through `ThemeCustomizations.apply_option/4`), the stored
  setting that holds the current choice, and the choices. `nil` hides the
  wizard's choice row.
  """
  @type onboarding_choices ::
          nil
          | %{
              group: atom(),
              field: String.t(),
              setting: String.t(),
              choices: [%{value: String.t(), name: String.t(), swatch: String.t()}]
            }

  @doc "The option groups the theme offers, in dashboard panel order."
  @callback option_groups() :: [OptionGroup.group()]

  @doc "The theme's defaults, keyed by setting name. The only place they live."
  @callback defaults() :: %{optional(atom()) => term()}

  @doc """
  Casts and validates the theme's settings. The changeset is a schemaless one
  over `setting_types/1`, holding as its data the stored settings as
  `Specs.settings/2` reads them, so the spec works with plain `cast/3`,
  `get_field/2` and `add_error/3`; the schema stores the result in its
  `settings` map. Rejects any option or value the theme does not support.
  Generated by `use`: every group's `changeset/3`.
  """
  @callback changeset(Changeset.t(), map()) :: Changeset.t()

  @doc """
  Resolves stored settings plus per-page-view overrides to CSS tokens and
  media. Generated by `use`: `Specs.tokens/3`.
  """
  @callback tokens(settings(), overrides()) :: Tokens.t()

  @doc """
  The settings that hold uploaded files, and the kind of each, for upload
  handling and clean-up. Generated by `use`: every group's `asset_fields/1`.
  Each field belongs to the group that declares it; an upload into it saves
  that group's `upload_changes/3` (`Specs.upload_group/2`).
  """
  @callback asset_fields() :: [{atom(), asset_kind()}]

  @doc """
  What the onboarding wizard lets the organiser pick for this theme.
  `use Spec` generates it from the palette group (`Specs.palette_choices/1`);
  `nil` when there is none.
  """
  @callback onboarding_choices() :: onboarding_choices()

  @optional_callbacks onboarding_choices: 0

  @doc false
  defmacro __using__(_opts) do
    quote do
      @behaviour unquote(__MODULE__)
      @after_compile unquote(__MODULE__)

      @impl unquote(__MODULE__)
      def changeset(changeset, attrs) do
        Enum.reduce(option_groups(), changeset, fn group, acc ->
          group.module.changeset(acc, attrs, group)
        end)
      end

      @impl unquote(__MODULE__)
      def asset_fields, do: Enum.flat_map(option_groups(), &OptionGroup.asset_fields/1)

      @impl unquote(__MODULE__)
      def tokens(settings, overrides), do: Specs.tokens(__MODULE__, settings, overrides)

      @impl unquote(__MODULE__)
      def onboarding_choices, do: Specs.palette_choices(__MODULE__)

      defoverridable changeset: 2, asset_fields: 0, tokens: 2, onboarding_choices: 0
    end
  end

  # Runs once the spec has compiled and loaded, the first moment its
  # `option_groups/0` can be called. Every group writes into the one
  # `settings` map, so a setting two groups declare would be overwritten by
  # one of them, and a key two groups share leaves the second unreachable by
  # `ThemeCustomizations.apply_option/4`. The calls happen here, not in the
  # spec's code, so they add no compile-time dependency.
  @doc false
  @spec __after_compile__(Macro.Env.t(), binary()) :: :ok
  def __after_compile__(env, _bytecode) do
    case clashes(env.module.option_groups()) do
      [] ->
        :ok

      clashes ->
        raise CompileError,
          file: env.file,
          line: env.line,
          description: "#{inspect(env.module)} #{Enum.join(clashes, "; ")}"
    end
  end

  defp clashes(groups) do
    settings =
      groups
      |> Enum.flat_map(fn %{key: key, module: module} ->
        Enum.map(module.types(), fn {setting, _type} -> {setting, key} end)
      end)
      |> Enum.group_by(&elem(&1, 0), &elem(&1, 1))
      |> Enum.filter(fn {_setting, keys} -> match?([_first, _second | _rest], keys) end)
      |> Enum.sort()
      |> Enum.map(fn {setting, keys} ->
        "declares the setting #{inspect(setting)} in more than one option group: " <>
          "#{inspect(keys)}; each setting belongs to one group (prefix a theme's own " <>
          "settings with its key)"
      end)

    keys =
      groups
      |> Enum.frequencies_by(& &1.key)
      |> Enum.filter(fn {_key, count} -> count > 1 end)
      |> Enum.sort()
      |> Enum.map(fn {key, _count} ->
        "declares the option group key #{inspect(key)} more than once"
      end)

    settings ++ keys
  end
end
