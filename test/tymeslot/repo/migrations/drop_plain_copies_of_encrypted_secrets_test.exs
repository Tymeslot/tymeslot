defmodule Tymeslot.Repo.Migrations.DropPlainCopiesOfEncryptedSecretsTest do
  @moduledoc """
  Covers the contract migration that drops the plain-text copies of secrets
  and link tokens kept by the encryption release.

  Each test rolls the migration back first, which brings the plain columns
  back filled from the encrypted ones (every row then matches), writes the
  state a rolled-back image would have left with raw SQL, and runs `up/0`
  over it. Tokens are checked through the application's own lookups, so a
  healed token is shown to resolve the way a visitor's link does. See
  `Tymeslot.Test.MigrationRunner`.
  """

  use Tymeslot.DataCase, async: false

  @moduletag :database
  @moduletag :security
  @moduletag :migrations

  alias Ecto.UUID
  alias Tymeslot.FreeBusy
  alias Tymeslot.Meetings.GuestQueries
  alias Tymeslot.Polls
  alias Tymeslot.Repo
  alias Tymeslot.Security.Encryption
  alias Tymeslot.Test.LogCapture
  alias Tymeslot.Test.MigrationRunner

  # Generated by `mix ecto.gen.migration drop_plain_copies_of_encrypted_secrets`.
  @version 20_261_012_214_443
  # The migration's `@page_size`: the rows it heals per query.
  @page_size 1_000

  @plain_columns [
    {"webhooks", "url"},
    {"video_integrations", "custom_meeting_url"},
    {"calendar_integrations", "google_channel_secret"},
    {"calendar_integrations", "graph_client_state"},
    {"telegram_integrations", "link_token"},
    {"polls", "token"},
    {"poll_participants", "token"},
    {"meeting_guests", "rsvp_token"},
    {"profiles", "freebusy_token"}
  ]

  @token_indexes [
    "polls_token_index",
    "poll_participants_token_index",
    "meeting_guests_rsvp_token_index",
    "profiles_freebusy_token_index",
    "telegram_integrations_link_token_index"
  ]

  describe "up" do
    test "drops every plain column and the unique indexes on the token columns" do
      MigrationRunner.down!(@version)
      assert Enum.all?(@plain_columns, &column_present?/1)
      assert Enum.all?(@token_indexes, &index_present?/1)

      MigrationRunner.up!(@version)

      assert Enum.filter(@plain_columns, &column_present?/1) == []
      assert Enum.filter(@token_indexes, &index_present?/1) == []
    end

    test "leaves a row whose plain and encrypted copies agree as it is" do
      webhook = insert(:webhook, url: "https://hooks.example.com/kept")
      MigrationRunner.down!(@version)
      ciphertext = raw("webhooks", webhook.id, "url_encrypted")
      assert raw("webhooks", webhook.id, "url") == "https://hooks.example.com/kept"

      MigrationRunner.up!(@version)

      assert raw("webhooks", webhook.id, "url_encrypted") == ciphertext
    end

    test "encrypts a plain value whose encrypted column is empty" do
      webhook = insert(:webhook)
      MigrationRunner.down!(@version)

      set_raw("webhooks", webhook.id,
        url: "https://hooks.example.com/written-after-rollback",
        url_encrypted: nil
      )

      MigrationRunner.up!(@version)

      assert decrypted("webhooks", webhook.id, "url") ==
               "https://hooks.example.com/written-after-rollback"
    end

    test "re-encrypts a plain value that differs from its encrypted copy" do
      integration =
        insert(:video_integration,
          provider: "custom",
          custom_meeting_url: "https://meet.example.com/old?pwd=1"
        )

      MigrationRunner.down!(@version)

      set_raw("video_integrations", integration.id,
        custom_meeting_url: "https://meet.example.com/new?pwd=2"
      )

      MigrationRunner.up!(@version)

      assert decrypted("video_integrations", integration.id, "custom_meeting_url") ==
               "https://meet.example.com/new?pwd=2"
    end

    test "re-encrypts a plain value beside an encrypted copy no key opens" do
      integration = insert(:calendar_integration)
      MigrationRunner.down!(@version)

      set_raw("calendar_integrations", integration.id,
        google_channel_secret: "channel-secret-from-rollback",
        google_channel_secret_encrypted: :crypto.strong_rand_bytes(64)
      )

      MigrationRunner.up!(@version)

      assert decrypted("calendar_integrations", integration.id, "google_channel_secret") ==
               "channel-secret-from-rollback"
    end

    test "heals and restores every row of a column longer than one page" do
      webhook = insert(:webhook)
      clone_rows("webhooks", webhook.id, @page_size)
      MigrationRunner.down!(@version)

      Repo.query!(
        "UPDATE webhooks SET url = 'https://hooks.example.com/' || id, url_encrypted = NULL"
      )

      MigrationRunner.up!(@version)

      %{rows: rows} = Repo.query!("SELECT id, url_encrypted FROM webhooks")
      assert length(rows) == @page_size + 1

      assert Enum.reject(rows, fn [id, ciphertext] ->
               Encryption.decrypt(ciphertext) == "https://hooks.example.com/#{id}"
             end) == []

      MigrationRunner.down!(@version)

      %{rows: restored} = Repo.query!("SELECT id, url FROM webhooks")
      assert length(restored) == @page_size + 1

      assert Enum.reject(restored, fn [id, url] -> url == "https://hooks.example.com/#{id}" end) ==
               []
    end

    test "a free/busy token issued by a rolled-back image resolves through the feed lookup" do
      profile = insert(:profile)
      MigrationRunner.down!(@version)
      token = "token-issued-after-rollback"
      set_raw("profiles", profile.id, freebusy_token: token)

      MigrationRunner.up!(@version)

      assert {:ok, %{id: id}} = FreeBusy.get_profile_by_token(token)
      assert id == profile.id
      assert decrypted("profiles", profile.id, "freebusy_token") == token
    end

    test "a free/busy token a rolled-back image regenerated replaces the old one" do
      {:ok, profile} = FreeBusy.enable_feed(insert(:profile))
      MigrationRunner.down!(@version)
      set_raw("profiles", profile.id, freebusy_token: "regenerated-after-rollback")

      MigrationRunner.up!(@version)

      assert {:ok, %{id: id}} = FreeBusy.get_profile_by_token("regenerated-after-rollback")
      assert id == profile.id
      assert {:error, :not_found} = FreeBusy.get_profile_by_token(profile.freebusy_token)
    end

    test "a poll link created by a rolled-back image resolves through the voting lookup" do
      poll = insert(:poll)
      MigrationRunner.down!(@version)
      token = "poll-link-from-rollback"
      set_raw("polls", poll.id, token: token, token_encrypted: nil, token_hash: nil)

      MigrationRunner.up!(@version)

      assert {:ok, %{id: id}} = Polls.get_poll_for_voting(token)
      assert id == poll.id
    end

    test "an RSVP link created by a rolled-back image resolves through the guest lookup" do
      {:ok, guest} =
        GuestQueries.insert_guest(%{meeting_id: insert(:meeting).id, email: "g@x.io"})

      MigrationRunner.down!(@version)
      token = "rsvp-link-from-rollback"

      set_raw("meeting_guests", guest.id,
        rsvp_token: token,
        rsvp_token_encrypted: nil,
        rsvp_token_hash: nil
      )

      MigrationRunner.up!(@version)

      assert {:ok, %{id: id}} = GuestQueries.get_by_token(token)
      assert id == guest.id
    end

    test "drops a Telegram link token as it is" do
      integration = insert(:telegram_integration, %{})
      MigrationRunner.down!(@version)
      set_raw("telegram_integrations", integration.id, link_token: "short-lived")

      MigrationRunner.up!(@version)

      refute column_present?({"telegram_integrations", "link_token"})
      assert raw("telegram_integrations", integration.id, "link_token_hash") == nil
    end

    test "logs one count per column and the Telegram tokens dropped, never a value" do
      plain_only = insert(:webhook)
      unreadable = insert(:webhook)
      _matching = insert(:webhook)
      telegram = insert(:telegram_integration, %{})
      MigrationRunner.down!(@version)

      set_raw("webhooks", plain_only.id,
        url: "https://hooks.example.com/secret-a",
        url_encrypted: nil
      )

      set_raw("webhooks", unreadable.id,
        url: "https://hooks.example.com/secret-b",
        url_encrypted: :crypto.strong_rand_bytes(64)
      )

      set_raw("telegram_integrations", telegram.id, link_token: "secret-telegram-token")

      events =
        LogCapture.with_capture([logger_level: :info], fn ->
          MigrationRunner.up!(@version)
          LogCapture.drain()
        end)

      webhooks = Enum.find(events, &(&1.meta[:column] == "webhooks.url"))

      telegram_event =
        Enum.find(events, &(&1.meta[:column] == "telegram_integrations.link_token"))

      assert %{healed: 2, healed_unreadable: 1} = webhooks.meta
      assert %{dropped: 1} = telegram_event.meta

      dumped = Enum.map_join(events, "\n", &inspect/1)
      refute dumped =~ "secret-a"
      refute dumped =~ "secret-b"
      refute dumped =~ "secret-telegram-token"
    end
  end

  describe "down" do
    test "restores each plain column from its encrypted copy" do
      webhook = insert(:webhook, url: "https://hooks.example.com/restored")
      {:ok, profile} = FreeBusy.enable_feed(insert(:profile))

      MigrationRunner.down!(@version)

      assert raw("webhooks", webhook.id, "url") == "https://hooks.example.com/restored"
      assert raw("profiles", profile.id, "freebusy_token") == profile.freebusy_token
    end

    test "leaves a value no key opens empty" do
      webhook = insert(:webhook)
      set_raw("webhooks", webhook.id, url_encrypted: :crypto.strong_rand_bytes(64))

      MigrationRunner.down!(@version)

      assert raw("webhooks", webhook.id, "url") == nil
    end

    test "recreates the unique index on a token column" do
      {:ok, profile} = FreeBusy.enable_feed(insert(:profile))
      other = insert(:profile)
      MigrationRunner.down!(@version)

      assert_raise Postgrex.Error, ~r/profiles_freebusy_token_index/, fn ->
        set_raw("profiles", other.id, freebusy_token: profile.freebusy_token)
      end
    end
  end

  defp column_present?({table, column}) do
    %{rows: [[count]]} =
      Repo.query!(
        """
        SELECT COUNT(*) FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = $1 AND column_name = $2
        """,
        [table, column]
      )

    count == 1
  end

  defp index_present?(name) do
    %{rows: [[count]]} =
      Repo.query!(
        "SELECT COUNT(*) FROM pg_indexes WHERE schemaname = current_schema() AND indexname = $1",
        [name]
      )

    count == 1
  end

  # Copies row `id` `count` times, every column but the primary key as it is.
  defp clone_rows(table, id, count) do
    %{rows: columns} =
      Repo.query!(
        """
        SELECT column_name FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = $1 AND column_name <> 'id'
        """,
        [table]
      )

    columns = Enum.map_join(columns, ", ", &~s("#{hd(&1)}"))

    Repo.query!(
      "INSERT INTO #{table} (#{columns}) SELECT #{columns} FROM #{table}, generate_series(1, $2) WHERE id = $1",
      [id, count]
    )
  end

  defp set_raw(table, id, values) do
    {assignments, params} =
      values
      |> Enum.with_index(2)
      |> Enum.map(fn {{column, value}, index} -> {"#{column} = $#{index}", value} end)
      |> Enum.unzip()

    Repo.query!(
      "UPDATE #{table} SET #{Enum.join(assignments, ", ")} WHERE id = $1",
      [dump_id(id) | params]
    )
  end

  defp raw(table, id, column) do
    %{rows: [[value]]} =
      Repo.query!("SELECT #{column} FROM #{table} WHERE id = $1", [dump_id(id)])

    value
  end

  defp decrypted(table, id, column),
    do: table |> raw(id, "#{column}_encrypted") |> Encryption.decrypt()

  # Postgrex takes a UUID as its 16 raw bytes.
  defp dump_id(id) when is_integer(id), do: id
  defp dump_id(id), do: UUID.dump!(id)
end
